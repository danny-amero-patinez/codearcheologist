describe('Anti-overclaim: cryptography rule', () => {
  test('CryptAcquireContextW alone produces at most MEDIUM confidence', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      imports: [{ dll: 'advapi32.dll', functions: ['CryptAcquireContextW'] }],
      evidence: [makeImportEvidence('advapi32.dll', ['CryptAcquireContextW'], 'evd-imp-0001')],
    };
    const inferences = cryptographicOperationsRule.evaluate(ctx);
    for (const inf of inferences) {
      expect(inf.confidence).not.toBe('high');
      expect(['medium', 'low', 'not-applicable']).toContain(inf.confidence);
    }
  });

  test('CryptAcquireContextW alone does not claim specific encrypted data flow', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      imports: [{ dll: 'advapi32.dll', functions: ['CryptAcquireContextW'] }],
      evidence: [makeImportEvidence('advapi32.dll', ['CryptAcquireContextW'], 'evd-imp-0001')],
    };
    const inferences = cryptographicOperationsRule.evaluate(ctx);
    for (const inf of inferences) {
      // Statement should NOT claim "encrypts data" or similar strong claim
      expect(inf.statement.toLowerCase()).not.toContain('encrypted data flow');
      // Limitations must reference this anti-overclaim
      const allLimitations = inf.limitations.join(' ').toLowerCase();
      expect(allLimitations).toContain('cryptacquirecontextw');
    }
  });
});

