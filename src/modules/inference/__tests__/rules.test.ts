describe('Anti-overclaim: function naming', () => {
  test('FUN_* function name has autoGenerated=true', () => {
    const fp = makeFunctionProfile('FUN_00401000', true);
    expect(fp.autoGenerated).toBe(true);
    expect(fp.name).toMatch(/^FUN_/);
  });

  test('FUN_* function name should never be treated as a recovered source name', () => {
    const fp = makeFunctionProfile('FUN_00401234', true);
    // autoGenerated=true means callers must not present this as a known source name
    expect(fp.autoGenerated).toBe(true);
  });
});

// ── Positive tests ────────────────────────────────────────────────────────────

describe('Positive: database inference', () => {
  test('ODBC APIs + SQL strings in same context → HIGH confidence', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      imports: [{ dll: 'odbc32.dll', functions: ['SQLConnectW', 'SQLExecDirectW', 'SQLFetch', 'SQLAllocHandle'] }],
      evidence: [
        makeImportEvidence('odbc32.dll', ['SQLConnectW', 'SQLExecDirectW', 'SQLFetch'], 'evd-imp-0001'),
        makeStringEvidence('SELECT id, name FROM users WHERE active=1', 'evd-str-0001'),
        makeStringEvidence('Driver={SQL Server};Server=localhost', 'evd-str-0002'),
      ],
      strings: [
        makeExtractedString('SELECT id, name FROM users WHERE active=1'),
        makeExtractedString('Driver={SQL Server};Server=localhost'),
      ],
    };
    const inferences = databaseInteractionRule.evaluate(ctx);
    expect(inferences).toHaveLength(1);
    expect(inferences[0]!.confidence).toBe('high');
    expect(inferences[0]!.ruleId).toBe('database-interaction');
  });
});

