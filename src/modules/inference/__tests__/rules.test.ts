// ── Helpers ────────────────────────────────────────────────────────────────────

function makeStringEvidence(value: string, id = `evd-str-${value.slice(0, 8)}`): Evidence {
  return {
    id,
    kind: 'string',
    sourceTool: 'strings',
    classification: 'observed',
    summary: `String: ${value}`,
    data: { value },
  };
}

function makeImportEvidence(dll: string, fns: string[], id: string): Evidence {
  return {
    id,
    kind: 'import',
    sourceTool: 'pe-parser',
    classification: 'observed',
    summary: `Import DLL: ${dll} (${fns.length} function(s))`,
    data: { dll, functions: fns },
  };
}

function makeExtractedString(value: string): ExtractedString {
  return {
    value,
    encoding: 'ascii',
    offset: 0,
    category: 'other',
  };
}

function makeFunctionProfile(name: string, autoGenerated = false): FunctionProfile {
  return {
    address: '0x00401000',
    name,
    autoGenerated,
    callers: [],
    callees: [],
    apiReferences: [],
    stringReferences: [],
    evidenceIds: [],
    decompilationEvidenceIds: [],
    selectionScore: 0,
    selectionReasons: [],
  };
}

function emptyCtx(): EvidenceContext {
  return { evidence: [], functionProfiles: [], imports: [], strings: [] };
}

// ── Anti-overclaim tests ──────────────────────────────────────────────────────

describe('Anti-overclaim: network rule', () => {
  test('SendMessageW + SendDlgItemMessageW do NOT produce network inference', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      imports: [{ dll: 'user32.dll', functions: ['SendMessageW', 'SendDlgItemMessageW', 'PostMessageW', 'SendMessageA', 'PostMessageA'] }],
      evidence: [makeImportEvidence('user32.dll', ['SendMessageW', 'SendDlgItemMessageW', 'PostMessageW'], 'evd-imp-0001')],
    };
    const inferences = networkCommunicationRule.evaluate(ctx);
    // These are Windows messaging APIs, NOT network — rule must produce nothing or only LOW
    const networkInferences = inferences.filter(i => i.confidence !== 'low');
    expect(networkInferences).toHaveLength(0);
    // Also: no medium or high inference should exist
    for (const inf of inferences) {
      expect(['low', 'not-applicable']).toContain(inf.confidence);
    }
  });

  test('Single URL string alone does NOT produce medium or high network inference', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      evidence: [makeStringEvidence('https://example.com/api', 'evd-str-0001')],
      strings: [makeExtractedString('https://example.com/api')],
    };
    const inferences = networkCommunicationRule.evaluate(ctx);
    for (const inf of inferences) {
      expect(inf.confidence).not.toBe('medium');
      expect(inf.confidence).not.toBe('high');
    }
  });

  test('URL string alone produces at most LOW confidence', () => {
    const ctx: EvidenceContext = {
      ...emptyCtx(),
      evidence: [makeStringEvidence('https://api.example.com/endpoint', 'evd-str-0001')],
      strings: [makeExtractedString('https://api.example.com/endpoint')],
    };
    const inferences = networkCommunicationRule.evaluate(ctx);
    if (inferences.length > 0) {
      expect(inferences[0]!.confidence).toBe('low');
    }
    // 0 or 1 low-confidence inference is acceptable
    expect(inferences.length).toBeLessThanOrEqual(1);
  });
});

